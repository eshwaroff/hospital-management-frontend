import { useState } from "react";

import {
  ArrowLeft,
  CalendarDays,
  Eye,
  EyeOff,
  Mail,
  MapPin,
  Phone,
  Stethoscope,
  UserRound,
} from "lucide-react";

import {
  useLocation,
  useNavigate,
} from "react-router-dom";

import AuthLayout from "../layouts/AuthLayout";
import {
  registerPatient,
  registerDoctor,
} from "../services/api/authApi";

import "../styles/Register.css";

function Register() {
  const navigate = useNavigate();
  const location = useLocation();

  const selectedRole =
    location.state?.role === "doctor"
      ? "doctor"
      : "patient";

  const [role, setRole] = useState(selectedRole);

  const [showPassword, setShowPassword] =
    useState(false);

  const [showConfirmPassword, setShowConfirmPassword] =
    useState(false);

  const [errors, setErrors] = useState({});
  const [loading, setLoading] = useState(false);
  const [success, setSuccess] = useState("");

  const [formData, setFormData] = useState({
    fullName: "",
    dob: "",
    gender: "",
    mobile: "",
    email: "",
    place: "",
    password: "",
    confirmPassword: "",

    specialization: "",
    qualification: "",
    experience: "",
    department: "",
  });

  const handleChange = (event) => {
    const { name, value } = event.target;

    setFormData((previous) => ({
      ...previous,
      [name]: value,
    }));

    if (errors[name]) {
      setErrors((previous) => ({
        ...previous,
        [name]: "",
      }));
    }

    setSuccess("");
  };

  const validateForm = () => {
    const newErrors = {};

    if (!formData.fullName.trim()) {
      newErrors.fullName =
        "Full name is required.";
    }

    if (!formData.dob) {
      newErrors.dob =
        "Date of birth is required.";
    }

    if (!formData.gender) {
      newErrors.gender =
        "Please select your gender.";
    }

    if (!formData.mobile.trim()) {
      newErrors.mobile =
        "Mobile number is required.";
    } else if (
      !/^[6-9]\d{9}$/.test(formData.mobile)
    ) {
      newErrors.mobile =
        "Enter a valid 10-digit mobile number.";
    }

    if (!formData.email.trim()) {
      newErrors.email =
        "Email is required.";
    } else if (
      !/^[^\s@]+@[^\s@]+\.[^\s@]+$/.test(
        formData.email
      )
    ) {
      newErrors.email =
        "Enter a valid email address.";
    }

    if (!formData.place.trim()) {
      newErrors.place =
        "Place is required.";
    }

    if (!formData.password) {
      newErrors.password =
        "Password is required.";
    } else if (formData.password.length < 8) {
      newErrors.password =
        "Password must be at least 8 characters.";
    }

    if (!formData.confirmPassword) {
      newErrors.confirmPassword =
        "Please confirm your password.";
    } else if (
      formData.password !==
      formData.confirmPassword
    ) {
      newErrors.confirmPassword =
        "Passwords do not match.";
    }

    if (role === "doctor") {
      if (!formData.specialization.trim()) {
        newErrors.specialization =
          "Specialization is required.";
      }

      if (!formData.qualification.trim()) {
        newErrors.qualification =
          "Qualification is required.";
      }

      if (!formData.experience) {
        newErrors.experience =
          "Experience is required.";
      }

      if (!formData.department.trim()) {
        newErrors.department =
          "Department is required.";
      }
    }

    return newErrors;
  };

  const handleSubmit = async (event) => {
    event.preventDefault();

    setErrors({});
    setSuccess("");

    const newErrors = validateForm();

    if (Object.keys(newErrors).length > 0) {
      setErrors(newErrors);
      return;
    }

    setLoading(true);

    try {
      /*
       * IDs are intentionally not sent.
       * Patient/Doctor IDs are generated by
       * the backend according to the requirements.
       */

      const registrationData = {
        fullName: formData.fullName,
        dob: formData.dob,
        gender: formData.gender,
        mobile: formData.mobile,
        email: formData.email,
        place: formData.place,
        password: formData.password,
      };

      let response;

      if (role === "patient") {
        response =
          await registerPatient(
            registrationData
          );
      } else {
        response =
          await registerDoctor({
            ...registrationData,
            specialization:
              formData.specialization,
            qualification:
              formData.qualification,
            experience:
              formData.experience,
            department:
              formData.department,
          });
      }

      console.log(
        "Registration successful:",
        response
      );

      setSuccess(
        "Account created successfully. You can now login."
      );

      setTimeout(() => {
        navigate(`/login/${role}`);
      }, 1200);
    } catch (error) {
      console.error(
        "Registration failed:",
        error
      );

      setErrors({
        submit:
          error.message ||
          "Unable to create account. Please try again.",
      });
    } finally {
      setLoading(false);
    }
  };

  return (
    <AuthLayout>
      <div className="register-card">

        <button
          type="button"
          className="back-button"
          onClick={() =>
            navigate(`/login/${role}`)
          }
        >
          <ArrowLeft size={17} />
          Back to login
        </button>

        <div className="register-header">
          <h2>Create your account</h2>

          <p>
            Register securely to access the
            CareConnect hospital portal.
          </p>
        </div>

        <div className="registration-role-section">
          <p className="section-label">
            Register as
          </p>

          <div className="registration-role-grid">

            <button
              type="button"
              className={`registration-role ${
                role === "patient"
                  ? "active"
                  : ""
              }`}
              onClick={() => {
                setRole("patient");
                setErrors({});
                setSuccess("");
              }}
            >
              <UserRound size={20} />

              <div>
                <strong>Patient</strong>
                <span>
                  Register as a patient
                </span>
              </div>
            </button>

            <button
              type="button"
              className={`registration-role ${
                role === "doctor"
                  ? "active"
                  : ""
              }`}
              onClick={() => {
                setRole("doctor");
                setErrors({});
                setSuccess("");
              }}
            >
              <Stethoscope size={20} />

              <div>
                <strong>Doctor</strong>
                <span>
                  Register as a doctor
                </span>
              </div>
            </button>

          </div>
        </div>

        {success && (
          <div className="register-success">
            {success}
          </div>
        )}

        {errors.submit && (
          <div className="register-error">
            {errors.submit}
          </div>
        )}

        <form
          onSubmit={handleSubmit}
          className="registration-form"
        >

          <div className="form-section">
            <h3>Personal information</h3>

            <div className="form-grid">

              <div className="form-group full-width">
                <label htmlFor="fullName">
                  Full Name
                </label>

                <div className="input-wrapper">
                  <UserRound size={18} />

                  <input
                    id="fullName"
                    name="fullName"
                    type="text"
                    placeholder="Enter your full name"
                    value={formData.fullName}
                    onChange={handleChange}
                    required
                  />
                </div>

                {errors.fullName && (
                  <span className="field-error">
                    {errors.fullName}
                  </span>
                )}
              </div>

              <div className="form-group">
                <label htmlFor="dob">
                  Date of Birth
                </label>

                <div className="input-wrapper">
                  <CalendarDays size={18} />

                  <input
                    id="dob"
                    name="dob"
                    type="date"
                    value={formData.dob}
                    onChange={handleChange}
                    required
                  />
                </div>

                {errors.dob && (
                  <span className="field-error">
                    {errors.dob}
                  </span>
                )}
              </div>

              <div className="form-group">
                <label htmlFor="gender">
                  Gender
                </label>

                <select
                  id="gender"
                  name="gender"
                  value={formData.gender}
                  onChange={handleChange}
                  required
                >
                  <option value="">
                    Select gender
                  </option>

                  <option value="male">
                    Male
                  </option>

                  <option value="female">
                    Female
                  </option>

                  <option value="other">
                    Other
                  </option>
                </select>

                {errors.gender && (
                  <span className="field-error">
                    {errors.gender}
                  </span>
                )}
              </div>

              <div className="form-group">
                <label htmlFor="mobile">
                  Mobile Number
                </label>

                <div className="input-wrapper">
                  <Phone size={18} />

                  <input
                    id="mobile"
                    name="mobile"
                    type="tel"
                    placeholder="Enter mobile number"
                    value={formData.mobile}
                    onChange={handleChange}
                    required
                  />
                </div>

                {errors.mobile && (
                  <span className="field-error">
                    {errors.mobile}
                  </span>
                )}
              </div>

              <div className="form-group">
                <label htmlFor="email">
                  Email
                </label>

                <div className="input-wrapper">
                  <Mail size={18} />

                  <input
                    id="email"
                    name="email"
                    type="email"
                    placeholder="Enter email address"
                    value={formData.email}
                    onChange={handleChange}
                    required
                  />
                </div>

                {errors.email && (
                  <span className="field-error">
                    {errors.email}
                  </span>
                )}
              </div>

              <div className="form-group full-width">
                <label htmlFor="place">
                  Place
                </label>

                <div className="input-wrapper">
                  <MapPin size={18} />

                  <input
                    id="place"
                    name="place"
                    type="text"
                    placeholder="Enter your city / place"
                    value={formData.place}
                    onChange={handleChange}
                    required
                  />
                </div>

                {errors.place && (
                  <span className="field-error">
                    {errors.place}
                  </span>
                )}
              </div>

            </div>
          </div>

          {role === "doctor" && (
            <div className="form-section">

              <h3>
                Professional information
              </h3>

              <div className="form-grid">

                <div className="form-group">
                  <label htmlFor="specialization">
                    Specialization
                  </label>

                  <input
                    id="specialization"
                    name="specialization"
                    type="text"
                    placeholder="e.g. Cardiology"
                    value={
                      formData.specialization
                    }
                    onChange={handleChange}
                    required
                  />

                  {errors.specialization && (
                    <span className="field-error">
                      {errors.specialization}
                    </span>
                  )}
                </div>

                <div className="form-group">
                  <label htmlFor="qualification">
                    Qualification
                  </label>

                  <input
                    id="qualification"
                    name="qualification"
                    type="text"
                    placeholder="e.g. MBBS, MD"
                    value={
                      formData.qualification
                    }
                    onChange={handleChange}
                    required
                  />

                  {errors.qualification && (
                    <span className="field-error">
                      {errors.qualification}
                    </span>
                  )}
                </div>

                <div className="form-group">
                  <label htmlFor="experience">
                    Experience
                  </label>

                  <input
                    id="experience"
                    name="experience"
                    type="number"
                    min="0"
                    placeholder="Years of experience"
                    value={
                      formData.experience
                    }
                    onChange={handleChange}
                    required
                  />

                  {errors.experience && (
                    <span className="field-error">
                      {errors.experience}
                    </span>
                  )}
                </div>

                <div className="form-group">
                  <label htmlFor="department">
                    Department
                  </label>

                  <input
                    id="department"
                    name="department"
                    type="text"
                    placeholder="Enter department"
                    value={
                      formData.department
                    }
                    onChange={handleChange}
                    required
                  />

                  {errors.department && (
                    <span className="field-error">
                      {errors.department}
                    </span>
                  )}
                </div>

              </div>
            </div>
          )}

          <div className="form-section">

            <h3>Account security</h3>

            <div className="form-grid">

              <div className="form-group">
                <label htmlFor="password">
                  Password
                </label>

                <div className="input-wrapper">

                  <input
                    id="password"
                    name="password"
                    type={
                      showPassword
                        ? "text"
                        : "password"
                    }
                    placeholder="Create a password"
                    value={formData.password}
                    onChange={handleChange}
                    required
                  />

                  <button
                    type="button"
                    className="password-toggle"
                    onClick={() =>
                      setShowPassword(
                        !showPassword
                      )
                    }
                  >
                    {showPassword ? (
                      <EyeOff size={18} />
                    ) : (
                      <Eye size={18} />
                    )}
                  </button>

                </div>

                {errors.password && (
                  <span className="field-error">
                    {errors.password}
                  </span>
                )}
              </div>

              <div className="form-group">
                <label htmlFor="confirmPassword">
                  Confirm Password
                </label>

                <div className="input-wrapper">

                  <input
                    id="confirmPassword"
                    name="confirmPassword"
                    type={
                      showConfirmPassword
                        ? "text"
                        : "password"
                    }
                    placeholder="Confirm your password"
                    value={
                      formData.confirmPassword
                    }
                    onChange={handleChange}
                    required
                  />

                  <button
                    type="button"
                    className="password-toggle"
                    onClick={() =>
                      setShowConfirmPassword(
                        !showConfirmPassword
                      )
                    }
                  >
                    {showConfirmPassword ? (
                      <EyeOff size={18} />
                    ) : (
                      <Eye size={18} />
                    )}
                  </button>

                </div>

                {errors.confirmPassword && (
                  <span className="field-error">
                    {errors.confirmPassword}
                  </span>
                )}
              </div>

            </div>
          </div>

          <button
            type="submit"
            className="register-button"
            disabled={loading}
          >
            {loading
              ? "Creating account..."
              : "Create Account"}
          </button>

        </form>
      </div>
    </AuthLayout>
  );
}

export default Register;